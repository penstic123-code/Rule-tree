const rulesText = (entry, lang = 'zh') => (lang === 'en' ? rulesTextEn(entry) : rulesTextZh(entry));

function guideText(lang = 'zh') {
  if (lang === 'en') {
    return [
      MARKS.en,
      '## RuleTree: requirements and rules for this project',
      `Each file in ${DIR}/ is one requirement. The file name is a number and a title (R1.2 is a child of R1). The first line holds the title and status (✅ done 🔨 in progress ⏳ to do ❓ undecided), the list items below it are the rules, and a "Docs:" line names background documents to read before you start (for a long document, read only the relevant sections). The rules of a requirement load automatically when you touch a file it covers. When you discuss a requirement but have not touched its files yet, read its file first; before creating a file, read the file of the requirement it belongs to. Read only the requirements related to the files you will change, not the whole folder. _root.md holds the rules for the whole project.`,
      ...rulesTextEn('CLAUDE.md'),
    ].join('\n') + '\n';
  }
  return [
    MARKS.zh,
    '## RuleTree：本项目的需求和规则',
    `${DIR}/ 里每个文件是一个需求：文件名是编号和标题（R1.2 是 R1 的下级），开头一行是标题和状态（✅完成 🔨进行中 ⏳待做 ❓待定），下面的列表项是规则，「文档：」一行是动手前要读的背景文档（长文档只读相关的节）。改到某个需求管的文件时，它的规则会自动加载；讨论某个需求、还没碰它的文件时，先读这里对应的文件；新建文件前，先读它所属需求的文件。只读和要改的文件有关的需求，不要把整个文件夹读一遍。_root.md 是全项目都要守的规则。`,
    ...rulesText('CLAUDE.md'),
  ].join('\n') + '\n';
}

const guidePath = dir => path.join(store.rulesDir(dir), '_guide.md');
// 说明书和这一版不一样（没有、旧版本、被手改）就重写。只在项目已经有规则文件时写。返回写了没有
// lang 只是默认语言：项目里已有说明书或规则时跟着它们走（detectLang），所以中文项目不会因为用户界面是英文就变英文
function ensureGuide(dir, { lang = 'en' } = {}) {
  if (!store.hasRules(dir)) return false;
  const want = guideText(detectLang(dir, lang));
  let have = null;
  try { have = fs.readFileSync(guidePath(dir), 'utf8'); } catch {}
  if (have === want) return false;
  // 文件里是更新版本写的（比如别的窗口装了新插件），旧插件不要改回去，免得来回改
  const ver = have && /^<!-- ruletree:guide (\d+)/.exec(have);
  if (ver && Number(ver[1]) > VERSION) return false;
  store.atomicWrite(guidePath(dir), want);
  return true;
}

module.exports = { VERSION, MARK, MARKS, DIR, rulesText, guideText, guidePath, ensureGuide };
